#!/usr/bin/env python3
"""Generate one wiki page per action, from the OpenAPI spec.

There is a page per browser action — sixteen of them — each with a tool and an
endpoint, and a set described by hand would be wrong within a month. The spec is already
generated from the live MCP tool schemas and a test fails when it goes stale, so
it is the one description of the surface that cannot drift — these pages are
rendered from it for the same reason.

The spec is built in-process rather than read off disk. ``openapi.yaml`` is a
generated artifact and is not committed, so depending on the file would mean
this script could only run after another one had written it — and could render
a wiki from a stale copy if it had not.

What is NOT generated is the prose: every page ends by including a hand-written
fragment from ``docs/notes/<tool>.notes.md`` when one exists, so guidance a
schema cannot express has somewhere to live that regeneration will not flatten.

    python scripts/generate_wiki.py            # write the pages
    python scripts/generate_wiki.py --check    # fail if they are out of date
"""

from __future__ import annotations

import argparse
import asyncio
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from kubed.selenium_flow import config
from kubed.selenium_flow.config import Settings
from kubed.selenium_flow.core.capabilities import CAPABILITIES, ENDPOINTS
from kubed.selenium_flow.server import SeleniumMCP
from kubed.selenium_flow.spec import build_spec

WIKI = REPO / "docs"
NOTES = WIKI / "notes"
# A GitHub wiki addresses a page by basename whatever directory it sits in, so
# a note named `<tool>.md` would shadow its page.
NOTES_SUFFIX = ".notes.md"

BANNER = (
    "<!-- Generated by scripts/generate_wiki.py from the OpenAPI spec. Do not edit:\n"
    "     prose belongs in docs/notes/{name}.notes.md, which is included below. -->"
)

# Configuration.md is built from the settings schema, not the OpenAPI spec.
CONFIG_BANNER = (
    "<!-- Generated by scripts/generate_wiki.py from the config schema in\n"
    "     kubed/selenium_flow/config.py. Do not edit: prose belongs in\n"
    "     docs/notes/Configuration.notes.md, which is included below. -->"
)

# The surfaces in the order a reader meets them: open a browser, do something,
