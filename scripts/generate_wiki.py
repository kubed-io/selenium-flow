ORDER = [tool for _, _, tools in GROUPS for tool in tools]


async def _build() -> dict:
    # A token so the security scheme is described; the address is never dialled.
    server = SeleniumMCP(
        Settings(grid={"url": "http://grid.invalid:4444"}, auth={"token": "generated"})
    )
    return await build_spec(server.mcp, ENDPOINTS, "", authenticated=True)


def load() -> dict:
    """The spec, straight from the live tool schemas."""
    return asyncio.run(_build())


def resolve(spec: dict, node: dict) -> dict:
    """Follow a local $ref, once: the spec never nests them deeper."""
    ref = node.get("$ref")
    if not ref:
        return node
    return spec["components"]["schemas"][ref.rsplit("/", 1)[-1]]


def type_of(field: dict) -> str:
    """A field's type, with the null branch read as optionality instead.

    ``anyOf: [string, null]`` is how an optional argument arrives from the tool
    schema, and printing it verbatim would tell a reader about JSON Schema
    rather than about the parameter.
    """
    branches = field.get("anyOf")
    if branches:
        # A branch is a plain type or a reference to a model: an optional typed
        # parameter arrives as `anyOf: [{$ref: ...}, {type: null}]`.
        names = [_named(b) for b in branches if b.get("type") != "null"]
        return " or ".join(n for n in names if n) or "any"
    declared = field.get("type")
    if isinstance(declared, list):
        # `type: [string, null]`, OpenAPI 3.1's other spelling of the same.
        names = [n for n in declared if n != "null"]
        return " or ".join(names) or "any"
    if declared:
        return declared
    if "$ref" in field:
        return field["$ref"].rsplit("/", 1)[-1]
    return "any"


def _named(branch: dict) -> str:
    """One schema branch as a type name: its own, or the model it points at."""
    if "$ref" in branch:
        return branch["$ref"].rsplit("/", 1)[-1]
    declared = branch.get("type")
    if isinstance(declared, list):
        return " or ".join(n for n in declared if n != "null")
    return declared or ""


def default_of(field: dict) -> str:
    if "default" not in field or field["default"] is None:
        return "—"
    value = field["default"]
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    return f"`{value}`"


def clean(text: str | None) -> str:
    """Collapse a docstring's hard wrapping into flowing markdown."""
    if not text:
        return ""
    out = []
    for block in text.split("\n\n"):
        stripped = block.strip("\n")
        # A code block or a list keeps its line breaks; prose does not.
        if stripped.lstrip().startswith(("- ", "* ", "|", "```", "    ")):
            out.append(stripped)
        else:
            out.append(" ".join(line.strip() for line in stripped.splitlines()))
    return "\n\n".join(b for b in out if b)


def table(rows: list[list[str]], head: list[str]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def parameters(spec: dict, schema: dict) -> str:
    props = schema.get("properties") or {}
    if not props:
        return "_This action takes no parameters._"
    required = set(schema.get("required") or [])
    rows = []
    for name, field in props.items():
        note = clean(field.get("description")) or ""
        mark = "**yes**" if name in required else "no"
        rows.append([f"`{name}`", type_of(field), mark, default_of(field), note])
    # Argument descriptions come from Python signatures, which have none, so the
    # column is usually empty. An empty column is worse than no column.
    if not any(row[-1] for row in rows):
        return table(
            [row[:-1] for row in rows], ["Name", "Type", "Required", "Default"]
        )
    return table(rows, ["Name", "Type", "Required", "Default", "Notes"])


def returns(spec: dict, schema: dict) -> str:
    props = schema.get("properties") or {}
    if not props:
        return "_An object._"
    rows = [
        [f"`{name}`", type_of(field), clean(field.get("description")) or ""]
        for name, field in props.items()
    ]
    return table(rows, ["Field", "Type", "Notes"])


def sample_of(spec: dict, field: dict, depth: int = 0) -> object:
    """One value of the right shape for ``field``, so an example can be sent.

    A schema's own ``example`` wins: that is how `steps` gets a step naming a
    tool that exists.
    """
    field = resolve(spec, field)
    if "example" in field:
        return field["example"]
    if "enum" in field:
        return field["enum"][0]

    declared = field.get("type")
    if isinstance(declared, list):
        declared = next((d for d in declared if d != "null"), None)
    if declared is None:
        for branch in field.get("anyOf") or []:
            if branch.get("type") != "null":
                return sample_of(spec, branch, depth)

    # Two levels is every shape this surface has, and stops a self-referential
    # schema from rendering forever.
    if declared == "array":
        if depth >= 2:
            return []
        return [sample_of(spec, field.get("items") or {}, depth + 1)]
    if declared == "object":
        props = field.get("properties") or {}
        if depth >= 2 or not props:
            return {}
        wanted = field.get("required") or list(props)[:1]
        return {n: sample_of(spec, props[n], depth + 1) for n in wanted if n in props}
    return {"string": "…", "integer": 0, "number": 0, "boolean": True}.get(
        declared, "…"
    )


def example(
    spec: dict, tool: str, method: str, path: str, schema: dict, in_path=(), uri=""
) -> str:
    """A call in both shapes, using only the parameters that are required.

    `in_path` names the parameters that travel in the URL: the MCP line shows
    them and the curl body does not.
    """
    required = list(schema.get("required") or [])
    props = schema.get("properties") or {}
    sample = {name: sample_of(spec, props.get(name, {})) for name in required}
    body = {k: v for k, v in sample.items() if k not in set(in_path)}
    mcp_args = ", ".join(
        f'{k}="{v}"' if isinstance(v, str) else f"{k}={json.dumps(v)}"
        for k, v in sample.items()
    )
    # ensure_ascii=False below, or the placeholder renders as `"\u2026"`.
    url = (
        path.replace("{name}", "my-flow")
        .replace("{action}", "click")
        .replace("{folder}", "screenshots")
    )
    lines = [
        f"curl -X {method} $SELENIUM_FLOW{url} \\",
        '  -H "Authorization: Bearer $TOKEN" \\',
        # The workspace is a header on both surfaces, so every example shows it.
        '  -H "Sf-Workspace: $WORKSPACE"',
    ]
    if body:
        encoded = json.dumps(body, indent=2, ensure_ascii=False)
        payload = "\n  ".join(encoded.splitlines())
        lines[-1] += " \\"
        lines += ["  -H 'Content-Type: application/json' \\", f"  -d '{payload}'"]
    body = "\n".join(lines)
    if uri:
        # A read is a resource over MCP, or `read_resource` for a client that
        # cannot read resources.
        read = uri.replace("{name}", "my-flow")
        mcp = f"read {read}\n\nread_resource(uri=\"{read}\")"
    else:
        mcp = f"{tool}({mcp_args})"
    return (
        f"**MCP**\n\n```\n{mcp}\n```\n\n"
        f"**HTTP**\n\n```bash\n{body}\n```"
    )


def failures(op: dict) -> str:
    """The error codes this endpoint declares, and what each means: the
    surfaces do not fail alike."""
    rows = [
        [f"`{code}`", clean(body.get("description"))]
        for code, body in sorted(op.get("responses", {}).items())
        if code != "200"
    ]
    if not rows:
        return ""
    return (
        "\n## Errors\n\n"
        + table(rows, ["Status", "Means"])
        + "\n\nOver MCP the same failures arrive as a tool error.\n"
    )


def render(spec: dict, tool: str, method: str, path: str, op: dict) -> str:
    uri = op.get("x-mcp-resource", "")
    # A GET or a DELETE has no body: what it takes is in the path and the
    # workspace header, so there is nothing to resolve.
    body = op.get("requestBody")
    request = (
        resolve(spec, body["content"]["application/json"]["schema"]) if body else {}
    )
    # A path parameter is still an argument of the tool: `GET /flows/{name}`
    # takes a name outside the body.
    in_path = [p for p in op.get("parameters", []) if p.get("in") == "path"]
    if in_path:
        request = {
            **request,
            "properties": {
                **{
                    p["name"]: {
                        **p.get("schema", {}),
                        "description": p.get("description", ""),
                    }
                    for p in in_path
                },
                **(request.get("properties") or {}),
            },
            "required": [p["name"] for p in in_path]
            + list(request.get("required") or []),
        }
    response = resolve(
        spec, op["responses"]["200"]["content"]["application/json"]["schema"]
    )
    description = clean(op.get("description"))
    summary = clean(op.get("summary"))
    # The summary is the description's first line, so printing both repeats it.
    if description.startswith(summary):
        description = description[len(summary) :].strip()

    note = NOTES / f"{tool}{NOTES_SUFFIX}"
    extra = f"\n\n{note.read_text().strip()}\n" if note.is_file() else ""

    return f"""{BANNER.format(name=tool)}

# `{uri or tool}`

> {summary}

|  |  |
|---|---|
| {"**MCP resource**" if uri else "**MCP tool**"} | `{uri or tool}` |
| **HTTP** | `{method} {path}` |

{description}

## Parameters

{parameters(spec, request)}

## Returns

{returns(spec, response)}
{failures(op)}
## Example

{example(spec, tool, method, path, request, [p["name"] for p in in_path], uri)}
{extra}
---

[← All actions](Actions) · [Installing](Installing) · [Deployment](Deployment)
"""


def page_name(op: dict) -> str:
    """What an operation's page is called: its tool, or for a read (a
    resource over MCP, with no tool) its operationId in the same snake case.
    """
    if op.get("x-mcp-tool"):
        return op["x-mcp-tool"]
    if op.get("x-mcp-resource"):
        return re.sub(r"(?<!^)(?=[A-Z])", "_", op["operationId"]).lower()
    return ""


def _default_of(leaf: config.Leaf) -> str:
    if leaf.default in (None, "", []):
        return "—"
    is_bool = isinstance(leaf.default, bool)
    value = str(leaf.default).lower() if is_bool else leaf.default
    return f"`{value}`"


def configuration() -> str:
    """Every setting, from the schema: the page a person reads to configure it."""
    by_section: dict[str, list] = {name: [] for name in config.SECTION_ORDER}
    for leaf in config.leaves():
        what = leaf.description + (" **Sensitive.**" if leaf.sensitive else "")
        row = [f"`{leaf.path}`", f"`{leaf.env}`", f"`{leaf.flag}`", _default_of(leaf)]
        by_section[leaf.section].append([*row, what])
    head = ["Config", "Env", "Flag", "Default", "What"]
    sections = [
        f"## {name}\n\n{config.SECTION_DESCRIPTIONS[name]}\n\n"
        + table(by_section[name], head)
        for name in config.SECTION_ORDER
    ]
    notes = NOTES / f"Configuration{NOTES_SUFFIX}"
    tail = f"\n\n---\n\n{notes.read_text().strip()}\n" if notes.is_file() else "\n"
    intro = (
        "Every setting can be set in a YAML config file, in the environment, or "
        "on the command line, and a later one wins: **default < config < env < "
        "args**. A setting's file path is its name: `redis.host` is "
        "`REDIS_HOST` and `--redis-host`.\n\n"
        "The file is named by `--config-file` or `CONFIG_FILE`. There is no "
        "default location. A file with an unknown key stops the server with "
        "the reason.\n\n"
    )
    return (
        f"{CONFIG_BANNER}\n\n# Configuration\n\n"
        + intro
        + "\n\n".join(sections)
        + tail
    )


def pages(spec: dict) -> dict[str, str]:
    by_tool = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            # An operation is worth a page when a caller can also reach it over
            # MCP (`x-mcp-tool` or `x-mcp-resource`), which leaves /health out.
            tool = page_name(op)
            if tool:
                by_tool[tool] = (method.upper(), path, op)

    # Every capability gets a page: a row the spec left out breaks the build.
    capabilities = {row.name for row in CAPABILITIES}
    undocumented = capabilities - set(by_tool)
    if undocumented:
        raise SystemExit(
            f"no operation in the spec for: {', '.join(sorted(undocumented))}"
        )
    missing = (set(by_tool) | capabilities) - set(ORDER)
    if missing:
        raise SystemExit(
            f"add these to GROUPS in {__file__}: {', '.join(sorted(missing))}"
        )

    out = {}
    for tool in ORDER:
        if tool not in by_tool:
            continue
        method, endpoint, op = by_tool[tool]
        out[f"{tool}.md"] = render(spec, tool, method, endpoint, op)

    sections = []
    for title, blurb, tools in GROUPS:
        rows = [
            [
                f"[`{by_tool[tool][2].get('x-mcp-resource') or tool}`]({tool})",
                f"`{by_tool[tool][0]} {by_tool[tool][1]}`",
                clean(by_tool[tool][2].get("summary")),
            ]
            for tool in tools
            if tool in by_tool
        ]
        if rows:
            sections.append(
                f"## {title}\n\n{blurb}\n\n{table(rows, ['MCP', 'Endpoint', 'Does'])}"
            )

    body = "\n\n".join(sections)
    out["Actions.md"] = f"""{BANNER.format(name="Actions")}

# Actions

Every action is an MCP tool **and** an HTTP endpoint with the same parameters,
and every read is an MCP resource **and** an HTTP endpoint. A test fails the
build if one exists without the other. A client that cannot read resources reads
the same URIs with `read_resource`.

{body}

A call names its workspace with an `Sf-Workspace` header or `?workspace=` on the
URL, and an unnamed caller can only read the shared flow library. No call takes
a session id; see [Workspaces](Workspaces).

---

[Installing](Installing) · [Deployment](Deployment) · [Administration](Administration)
"""
    out["Configuration.md"] = configuration()
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if stale")
    args = parser.parse_args()

    if not WIKI.is_dir():
        raise SystemExit("docs/ is not checked out — run: git submodule update --init")

    rendered = pages(load())
    stale = []
    for name, body in rendered.items():
        target = WIKI / name
        if not target.is_file() or target.read_text() != body:
            stale.append(name)
        if not args.check:
            target.write_text(body)

    if args.check:
        if stale:
            print("stale wiki pages: " + ", ".join(stale), file=sys.stderr)
            print("run python scripts/generate_wiki.py", file=sys.stderr)
            return 1
        print(f"{len(rendered)} wiki pages up to date")
        return 0

    print(f"wrote {len(rendered)} pages to {WIKI}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
